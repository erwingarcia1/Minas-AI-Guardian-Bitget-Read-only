"""The Minas logo: every file is present, packaged, the size its platform
asks for, and served by the portal. The ops dashboard wears the same mark
(decision 24) through brand.py's markup and serves no file of its own: on
the shared hostname its pages point at the portal's paths.

Read with the PNG header alone (IHDR), because Pillow is not a dependency:
the files are generated by scripts/brand-assets.py and committed.
"""
from __future__ import annotations

import fnmatch
import http.client
import struct
import tomllib
from pathlib import Path

import pytest

from sentinel import brand, dashboard, metrics
from sentinel.portal import _render_login, serve_portal

ROOT = Path(__file__).resolve().parent.parent
PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"
RGB, RGBA = 2, 6  # PNG colour types: opaque, and with alpha


def _png(path: Path) -> tuple[int, int, int]:
    """(width, height, colour type) from the IHDR chunk."""
    head = path.read_bytes()[:26]
    assert head[:8] == PNG_SIGNATURE, f"{path} is not a PNG"
    assert head[12:16] == b"IHDR"
    width, height = struct.unpack(">II", head[16:24])
    return width, height, head[25]


@pytest.mark.parametrize("path, size, colour", [
    ("sentinel/static/minas-mark.png", 128, RGBA),
    ("sentinel/static/favicon.png", 64, RGBA),
    # Home-screen and store icons must fill the square: no alpha at all.
    ("sentinel/static/apple-touch-icon.png", 180, RGB),
    ("design/brand/app-icon.png", 1024, RGB),
    ("design/brand/android-foreground.png", 1024, RGBA),
    ("design/brand/android-monochrome.png", 1024, RGBA),
    ("design/brand/splash.png", 1024, RGBA),
    ("design/brand/minas-logo.png", 2048, RGBA),
])
def test_every_logo_file_is_the_size_its_platform_asks_for(path, size, colour):
    assert _png(ROOT / path) == (size, size, colour)


def test_the_play_graphics_are_what_play_console_asks_for():
    """Google Play's listing graphics (scripts/brand-assets.py store): the
    icon a 512 px 32-bit PNG under 1 MB, the feature graphic 1024 x 500
    with no alpha (Play refuses one with transparency)."""
    icon = ROOT / "mobile" / "store" / "play-icon.png"
    feature = ROOT / "mobile" / "store" / "play-feature-graphic.png"
    assert _png(icon) == (512, 512, RGBA) and icon.stat().st_size < 1024 * 1024
    assert _png(feature) == (1024, 500, RGB) and feature.stat().st_size < 15 * 1024 * 1024


def test_the_feature_graphic_says_what_the_landing_page_says():
    """Its one line of copy is the landing page's eyebrow (decision 25).
    The script runs without the service's dependencies, so it carries a
    copy; this keeps the copy honest."""
    import re

    from sentinel.portal import _render_landing

    script = (ROOT / "scripts" / "brand-assets.py").read_text()
    eyebrow = re.search(r'^EYEBROW = "([^"]+)"$', script, re.M).group(1)
    assert f'<span class="eyebrow">{eyebrow}</span>' in _render_landing()


def test_every_file_the_portal_serves_is_packaged():
    """`pip install .` (the Docker image) ships only what package-data
    names, and brand.py reads these at import: a file left out is a service
    that does not start."""
    globs = tomllib.loads((ROOT / "pyproject.toml").read_text())["tool"]["setuptools"]["package-data"]["sentinel"]
    static = sorted(p.relative_to(ROOT / "sentinel").as_posix() for p in brand.STATIC.iterdir())
    assert static, "nothing under sentinel/static - the scan proves nothing"
    for name in static:
        assert any(fnmatch.fnmatch(name, g) for g in globs), f"sentinel/{name} is not in package-data"
    assert set(brand.WEB_ASSETS.values()) <= {Path(n).name for n in static}


def test_the_old_mark_is_gone_from_every_page():
    """The portal's login, the dashboard's shell and both metrics renderings
    (decision 24 brought the last two onto the brand): the 2026-10-22 mark
    through brand.py's markup, never the retired stroked-infinity SVG, its
    gradient, its glow, its pulse or the old MINAS wordmark."""
    page = _render_login()
    assert brand.MARK_HTML in page and brand.ICON_LINKS in page
    assert "<svg class=\"brand__mark\"" not in page
    assert "MARK_SVG" not in (ROOT / "sentinel" / "portal.py").read_text()
    shell = dashboard._page("", "<p>x</p>")
    assert brand.MARK_HTML in shell and brand.ICON_LINKS in shell
    for rendering in (shell, metrics.render_metrics_body(), metrics.render_metrics_html()):
        assert "<svg class=\"brand__mark\"" not in rendering
        for retired in ('class="minas"', "linearGradient", "linear-gradient", "radial-gradient", "conic-gradient",
                        "box-shadow", "@keyframes"):
            assert retired not in rendering, retired
    assert "gradient" not in metrics._STANDALONE_STYLE.lower()
    assert brand.VIOLET.lower() in metrics._STANDALONE_STYLE.lower()
    assert "MARK_SVG" not in (ROOT / "sentinel" / "metrics.py").read_text()


